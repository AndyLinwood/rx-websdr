static void bp_draw_char(uint8_t *px, int x, int row_base,
                         unsigned char c, uint8_t color) {
    if (c >= 128) return;
    for (int r = 0; r < 8; r++) {
        uint8_t bits = BP_FONT[c][r];
        for (int col = 0; col < 6; col++) {
            if (bits & (0x20 >> col)) {
                int X = x + col, Y = row_base + r;
                if (X >= 0 && X < SCALE_W && Y >= 0 && Y < SCALE_H)
                    px[Y * SCALE_W + X] = color;
            }
        }
    }
}

static void bp_draw_str(uint8_t *px, int x, int row_base,
                        const char *s, uint8_t color) {
    int cx = x;
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        bp_draw_char(px, cx, row_base, *p, color);
        cx += 7;   /* 6px glyph + 1px advance */
    }
}

static void bp_overlay(uint8_t *px, double f_lo_khz, double f_hi_khz) {
    double span = f_hi_khz - f_lo_khz;
    if (span <= 0.0) return;

    for (size_t i = 0; i < sizeof(bp_entries)/sizeof(bp_entries[0]); i++) {
        const struct BPEntry *e = &bp_entries[i];
        double lo = e->min_khz > f_lo_khz ? e->min_khz : f_lo_khz;
        double hi = e->max_khz < f_hi_khz ? e->max_khz : f_hi_khz;
        if (hi <= lo) continue;

        int x0 = (int)((lo - f_lo_khz) / span * SCALE_W + 0.5);
        int x1 = (int)((hi - f_lo_khz) / span * SCALE_W + 0.5);
        if (x1 <= x0) x1 = x0 + 1;
        if (x0 < 0) x0 = 0;
        if (x1 > SCALE_W) x1 = SCALE_W;

        /* solid background strip (rows 30..43) so the bar reads as one */
        for (int x = x0; x < x1; x++)
            for (int yy = 30; yy < SCALE_H; yy++)
                px[yy * SCALE_W + x] = 5;   /* black */

        for (int x = x0; x < x1; x++)
            px[BP_LINE_Y * SCALE_W + x] = e->color;

        int len = (int)strlen(e->short_label);
        int text_w = len * 7 - 1;
        int tx = (x0 + x1) / 2 - text_w / 2;
        if (tx < BP_MARGIN_X) tx = BP_MARGIN_X;
        if (tx + text_w >= SCALE_W - BP_MARGIN_X)
            tx = SCALE_W - BP_MARGIN_X - text_w - 1;
        if (tx >= BP_MARGIN_X && tx + text_w < SCALE_W - BP_MARGIN_X)
            bp_draw_str(px, tx, BP_TEXT_Y, e->short_label, e->color);
    }
}

